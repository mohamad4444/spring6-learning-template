-- Portable across H2 in PostgreSQL mode and PostgreSQL. Never edit applied migrations.
create table app_user (
    id uuid primary key,
    first_name varchar(255), last_name varchar(255),
    email varchar(255) not null unique, password varchar(255)
);
create table advanced_user_entity_roles (
    advanced_user_entity_id uuid not null references app_user(id), roles varchar(255)
);
create table jpa_note (id bigint generated by default as identity primary key, note varchar(255), tag varchar(255));
create table secured_note (id bigint generated by default as identity primary key, note varchar(255), tag varchar(255));
create table advanced_note (id bigint generated by default as identity primary key, note varchar(255), tag varchar(255), creator_id uuid);
create table users (id bigint generated by default as identity primary key, username varchar(255), password varchar(255), role varchar(255));
create table benutzer (
    id integer generated by default as identity primary key,
    vorname varchar(255), nachname varchar(255), benutzername varchar(255),
    password_hash bytea not null, password_salt bytea not null
);
create table notiz (
    id integer generated by default as identity primary key,
    datum timestamp(6), inhalt varchar(255), benutzer_id integer references benutzer(id)
);
create table task (
    id uuid primary key, title varchar(120) not null, description varchar(2000) not null,
    status varchar(20) not null, owner varchar(255) not null,
    version bigint not null, created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create index idx_task_owner_status on task(owner, status);
